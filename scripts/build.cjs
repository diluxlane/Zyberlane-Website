'use strict';

// Static-site packaging only: no templating, CMS requests or HTML rewrites.
const fs = require('node:fs');
const path = require('node:path');
const { ORIGIN, checkStructuredData } = require('./structured-data.cjs');
const INTERNAL = new Set(['assets', 'dist', 'docs', 'security', 'tests', 'scripts', 'node_modules']);
const ROOT_PUBLIC = /\.(?:html|txt|xml|ico|png|webmanifest)$/i;

function attributes(tag) {
  return Object.fromEntries(Array.from(tag.matchAll(/([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g), m =>
    [m[1].toLowerCase(), m[2] ?? m[3]]));
}

function pageInfo(file, html) {
  const meta = Array.from(html.matchAll(/<meta\b[^>]*>/gi), m => attributes(m[0]));
  if (meta.some(m => /^(?:robots|googlebot|bingbot)$/i.test(m.name || '') && /\bnoindex\b/i.test(m.content || ''))) return null;
  const canonicals = Array.from(html.matchAll(/<link\b[^>]*>/gi), m => attributes(m[0]))
    .filter(link => /(?:^|\s)canonical(?:\s|$)/i.test(link.rel || ''));
  // Ownership-verification files are copied verbatim and are never sitemap pages.
  if (!canonicals.length && /^(?:google[\w-]+|yandex_[\w-]+)\.html$/i.test(file)) return null;
  if (canonicals.length !== 1) throw new Error(file + ': expected one canonical');
  const url = new URL(canonicals[0].href);
  const expected = '/' + file.replace(/(?:^|\/)index\.html$/, match => match.startsWith('/') ? '/' : '');
  if (url.origin !== ORIGIN || url.pathname !== expected || url.search || url.hash) {
    throw new Error(file + ': canonical must be ' + ORIGIN + expected);
  }
  return url.href;
}

function xml(value) {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function build(root = path.resolve(__dirname, '..')) {
  const output = path.join(root, 'dist');
  const pages = [];
  const htmlFiles = [];
  const publicFiles = [];
  const pageSources = [];

  function discover(directory, relative = '') {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name.startsWith('.') || entry.isSymbolicLink()) continue;
      const file = path.posix.join(relative, entry.name);
      if (entry.isDirectory()) {
        if (!INTERNAL.has(entry.name)) discover(path.join(directory, entry.name), file);
      } else if (entry.isFile() && file.endsWith('.html')) {
        htmlFiles.push(file);
        const html = fs.readFileSync(path.join(root, file), 'utf8');
        const canonical = pageInfo(file, html);
        if (canonical) { pages.push(canonical); pageSources.push({ file, html }); }
        publicFiles.push(file);
      } else if (!relative && ROOT_PUBLIC.test(file) && file !== 'sitemap.xml') {
        publicFiles.push(file);
      }
    }
  }
  discover(root);
  pages.sort((a, b) => a === ORIGIN + '/' ? -1 : b === ORIGIN + '/' ? 1 : a.localeCompare(b));
  if (!pages.includes(ORIGIN + '/')) throw new Error('Missing canonical homepage');
  if (new Set(pages).size !== pages.length) throw new Error('Duplicate sitemap canonical');
  checkStructuredData(root, pageSources);

  // No invented lastmod: add dates only when a reliable content-modification source exists.
  const sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!-- Generated by node scripts/build.cjs from indexable HTML canonicals. -->\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    pages.map(url => '  <url><loc>' + xml(url) + '</loc></url>\n').join('') + '</urlset>\n';
  const redirects = '# Generated by node scripts/build.cjs. Keep the existing production hostname.\n' +
    'https://zyberlane.netlify.app/* https://zyberlane.com/:splat 301!\n' +
    'http://zyberlane.netlify.app/* https://zyberlane.com/:splat 301!\n' +
    htmlFiles.filter(file => /(?:^|\/)index\.html$/.test(file)).map(file => {
      const target = '/' + file.replace(/(?:^|\/)index\.html$/, match => match.startsWith('/') ? '/' : '');
      return '/' + file + ' ' + target + ' 301!\n';
    }).join('');

  // Validation completes before replacing the generated output.
  fs.rmSync(output, { recursive: true, force: true });
  fs.mkdirSync(output, { recursive: true });
  for (const file of publicFiles) {
    const target = path.join(output, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(path.join(root, file), target);
  }
  fs.cpSync(path.join(root, 'assets'), path.join(output, 'assets'), {
    recursive: true,
    filter: source => !path.relative(path.join(root, 'assets'), source).split(path.sep).some(part => part.startsWith('.')) && !fs.lstatSync(source).isSymbolicLink()
  });
  fs.copyFileSync(path.join(root, '_headers'), path.join(output, '_headers'));
  for (const [file, content] of [['sitemap.xml', sitemap], ['_redirects', redirects]]) {
    fs.writeFileSync(path.join(root, file), content);
    fs.writeFileSync(path.join(output, file), content);
  }
  return { output, pages, htmlFiles };
}

if (require.main === module) {
  const result = build();
  console.log('Built dist/: ' + result.pages.length + ' canonical public pages; admin retained with noindex; internal source excluded.');
}
module.exports = { build };
