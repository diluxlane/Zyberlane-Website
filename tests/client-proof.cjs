'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { build } = require('../scripts/build.cjs');
const root = path.resolve(__dirname, '..');
const origin = 'https://zyberlane.com';
const { output, pages } = build(root);
const route = '/work/divine-tattoo/';
const source = file => fs.readFileSync(path.join(root, file), 'utf8');
const built = file => fs.readFileSync(path.join(output, file), 'utf8');
const page = built('work/divine-tattoo/index.html');
const home = source('index.html');
const service = source('services/web-development/index.html');
const graph = JSON.parse(page.match(/<script type="application\/ld\+json" id="zyberlane-structured-data">([\s\S]*?)<\/script>/)[1])['@graph'];
const pageEntity = graph.find(node => node['@id'] === origin + route + '#webpage');
const project = graph.find(node => node['@id'] === origin + route + '#project');

assert.ok(pages.includes(origin + route), 'case study is discovered for the sitemap');
assert.equal((page.match(/<link rel="canonical" href="[^"]+">/g) || []).length, 1);
assert.match(page, new RegExp('<link rel="canonical" href="' + origin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + route.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '">'));
assert.match(page, /<title>Divine Tattoo Website Project \| Zyberlane<\/title>/);
assert.match(page, /<meta name="description" content="A real client project by Zyberlane:[^"]+">/);
assert.equal((page.match(/<h1\b/g) || []).length, 1);
assert.match(page, /<h1 id="pageTitle">Divine Tattoo<\/h1>/);
assert.match(page, /Client Project/);
assert.match(page, /responsive studio website[\s\S]*?artwork gallery[\s\S]*?content-management workflow/i);
assert.match(page, /href="https:\/\/divinetattoo\.netlify\.app\/" target="_blank" rel="noopener noreferrer"/);
assert.match(page, /href="\/services\/web-development\/"/);
assert.match(page, /href="\/#booking"/);
assert.match(page, /src="\/assets\/divine-tattoo-logo\.jpg"[^>]+alt="Divine Tattoo circular black, white and gold logo"/);
assert.ok(!page.includes('divine-tattoo-preview.jpg'), 'unverified metric screenshot is not reused');
assert.match(home, /data-project-category="client-projects"[\s\S]*?href="\/work\/divine-tattoo\/"/);
assert.match(home, /href="https:\/\/divinetattoo\.netlify\.app\/" target="_blank" rel="noopener noreferrer"/);
assert.match(service, /href="\/work\/divine-tattoo\/">Read the Divine Tattoo project case study<\/a>/);
assert.equal(pageEntity['@type'], 'WebPage');
assert.equal(pageEntity.mainEntity['@id'], project['@id']);
assert.equal(pageEntity.mentions['@id'], origin + '/#service-web-development');
assert.equal(project['@type'], 'CreativeWork');
assert.equal(project.creator['@id'], origin + '/#organization');
assert.equal(project.mainEntityOfPage['@id'], pageEntity['@id']);
assert.ok(!graph.some(node => ['Review', 'AggregateRating', 'CaseStudy', 'Article', 'LocalBusiness'].includes(node['@type'])));
assert.match(page, /“The design is modern, professional, clean, and perfectly matches my brand\.”/);
assert.match(page, /Asanka Mahesh[\s\S]*?Divine Tattoo[\s\S]*?https:\/\/maps\.app\.goo\.gl\/43SbLYGa6dmvyjkN6/);
assert.ok(!JSON.stringify(graph).includes('netlify.app'));
assert.ok(!built('sitemap.xml').includes('netlify.app'));
assert.match(built('sitemap.xml'), /<loc>https:\/\/zyberlane\.com\/work\/divine-tattoo\/<\/loc>/);
assert.ok(fs.existsSync(path.join(output, 'assets/divine-tattoo-logo.jpg')));
console.log('PASS: Divine Tattoo project route, client classification, canonical/metadata, factual scope, links, WebPage/CreativeWork/Service relationships, quote attribution, sitemap and no unsupported review markup.');
